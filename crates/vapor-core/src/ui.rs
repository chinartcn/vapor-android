//! 内置基础 UI（immediate-mode，纯 CPU 画到共享内存帧缓冲）。
//!
//! 进入渲染器默认显示：导入、文件管理、设置 三个入口。UI 绘制逻辑用 Rust 写，
//! Python 侧 `rust.Vapor.ui` 提供等价封装，扩展可完全替换/覆盖。
//! 所有绘制直接写帧缓冲，与 Python 的像素写操作共享同一块内存。

use crate::state::State;
use vapor_abi::VAPOR_OK;

/// 颜色为 0xAABBGGRR（与本帧缓冲 RGBA8888 字节序对应）。
fn put_px(buf: &mut [u8], w: i32, h: i32, x: i32, y: i32, color: u32) {
    if x < 0 || y < 0 || x >= w || y >= h { return; }
    let idx = ((y as usize) * (w as usize) + (x as usize)) * 4;
    if idx + 3 >= buf.len() { return; }
    buf[idx]     = (color & 0xFF) as u8;         // R
    buf[idx + 1] = ((color >> 8) & 0xFF) as u8;  // G
    buf[idx + 2] = ((color >> 16) & 0xFF) as u8; // B
    buf[idx + 3] = ((color >> 24) & 0xFF) as u8; // A
}

pub fn fill_rect(buf: &mut [u8], w: i32, h: i32, x: i32, y: i32, rw: i32, rh: i32, color: u32) {
    for yy in y..(y + rh) {
        for xx in x..(x + rw) {
            put_px(buf, w, h, xx, yy, color);
        }
    }
}

/// 5x7 点阵字形（仅 A-Z 0-9 与常见符号），用于无字体依赖时的基础文本。
fn glyph(c: u8) -> [u8; 7] {
    let g: &[u8] = match c {
        b'A' => &[0x0E,0x11,0x11,0x1F,0x11,0x11,0x11],
        b'B' => &[0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E],
        b'C' => &[0x0E,0x11,0x10,0x10,0x10,0x11,0x0E],
        b'D' => &[0x1E,0x11,0x11,0x11,0x11,0x11,0x1E],
        b'E' => &[0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F],
        b'F' => &[0x1F,0x10,0x10,0x1E,0x10,0x10,0x10],
        b'G' => &[0x0E,0x11,0x10,0x17,0x11,0x11,0x0F],
        b'H' => &[0x11,0x11,0x11,0x1F,0x11,0x11,0x11],
        b'I' => &[0x0E,0x04,0x04,0x04,0x04,0x04,0x0E],
        b'J' => &[0x07,0x02,0x02,0x02,0x02,0x12,0x0C],
        b'K' => &[0x11,0x12,0x14,0x18,0x14,0x12,0x11],
        b'L' => &[0x10,0x10,0x10,0x10,0x10,0x10,0x1F],
        b'M' => &[0x11,0x1B,0x15,0x15,0x11,0x11,0x11],
        b'N' => &[0x11,0x19,0x15,0x13,0x11,0x11,0x11],
        b'O' => &[0x0E,0x11,0x11,0x11,0x11,0x11,0x0E],
        b'P' => &[0x1E,0x11,0x11,0x1E,0x10,0x10,0x10],
        b'Q' => &[0x0E,0x11,0x11,0x11,0x15,0x12,0x0D],
        b'R' => &[0x1E,0x11,0x11,0x1E,0x14,0x12,0x11],
        b'S' => &[0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E],
        b'T' => &[0x1F,0x04,0x04,0x04,0x04,0x04,0x04],
        b'U' => &[0x11,0x11,0x11,0x11,0x11,0x11,0x0E],
        b'V' => &[0x11,0x11,0x11,0x11,0x11,0x0A,0x04],
        b'W' => &[0x11,0x11,0x11,0x15,0x15,0x1B,0x11],
        b'X' => &[0x11,0x11,0x0A,0x04,0x0A,0x11,0x11],
        b'Y' => &[0x11,0x11,0x0A,0x04,0x04,0x04,0x04],
        b'Z' => &[0x1F,0x01,0x02,0x04,0x08,0x10,0x1F],
        b'0' => &[0x0E,0x11,0x13,0x15,0x19,0x11,0x0E],
        b'1' => &[0x04,0x0C,0x04,0x04,0x04,0x04,0x0E],
        b'2' => &[0x0E,0x11,0x01,0x02,0x04,0x08,0x1F],
        b'3' => &[0x1F,0x02,0x04,0x0E,0x01,0x11,0x0E],
        b'4' => &[0x02,0x06,0x0A,0x12,0x1F,0x02,0x02],
        b'5' => &[0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E],
        b'6' => &[0x06,0x08,0x10,0x1E,0x11,0x11,0x0E],
        b'7' => &[0x1F,0x01,0x02,0x04,0x08,0x08,0x08],
        b'8' => &[0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E],
        b'9' => &[0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C],
        b'.' => &[0x00,0x00,0x00,0x00,0x00,0x0C,0x0C],
        b'-' => &[0x00,0x00,0x00,0x1F,0x00,0x00,0x00],
        b'/' => &[0x01,0x02,0x02,0x04,0x08,0x08,0x10],
        b' ' => &[0x00,0x00,0x00,0x00,0x00,0x00,0x00],
        _   => &[0x1F,0x11,0x11,0x11,0x11,0x11,0x1F],
    };
    let mut out = [0u8; 7];
    out.copy_from_slice(&g[..7]);
    out
}

pub fn draw_text(buf: &mut [u8], w: i32, h: i32, x: i32, y: i32, text: &str, scale: i32, color: u32) {
    let mut cx = x;
    for &b in text.as_bytes() {
        let rows = glyph(b.to_ascii_uppercase());
        for (ry, row) in rows.iter().enumerate() {
            for bit in 0..5 {
                if (row >> (4 - bit)) & 1 == 1 {
                    fill_rect(buf, w, h, cx + (bit as i32) * scale, y + (ry as i32) * scale, scale, scale, color);
                }
            }
        }
        cx += 6 * scale;
    }
}

/// 绘制默认主界面：标题 + 三个入口卡片。
pub fn draw_home(s: &mut State) {
    let (w, h) = (s.width, s.height);
    let bg = s.bg_color;
    // 背景
    fill_rect(&mut s.framebuffer, w, h, 0, 0, w, h, bg);
    // 顶栏
    fill_rect(&mut s.framebuffer, w, h, 0, 0, w, 72, 0xFF20262E);
    draw_text(&mut s.framebuffer, w, h, 24, 30, "VAPOR RENDERER", 3, 0xFFFFFFFF);

    let cards = ["IMPORT", "FILES", "SETTINGS"];
    let card_w = w - 48;
    let card_h = 96;
    let mut y = 112;
    for (i, label) in cards.iter().enumerate() {
        let accent = match i {
            0 => 0xFF3A7BD5,
            1 => 0xFF2E8B57,
            _ => 0xFF8B6B2E,
        };
        fill_rect(&mut s.framebuffer, w, h, 24, y, card_w, card_h, 0xFF2A323C);
        fill_rect(&mut s.framebuffer, w, h, 24, y, 8, card_h, accent);
        draw_text(&mut s.framebuffer, w, h, 56, y + 34, label, 3, 0xFFFFFFFF);
        y += card_h + 24;
    }
    draw_text(&mut s.framebuffer, w, h, 24, h - 56, "CPYTHON 3.15.2 / ABI 1", 2, 0xFF8A97A6);
}

